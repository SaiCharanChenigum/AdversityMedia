function updateLoadMoreButton() {
    const loadMoreContainer = document.getElementById('loadMoreContainer');
    const totalItems = filteredData.length;
    const itemsShown = currentPage * portfolioConfig.itemsPerPage;
    
    if (itemsShown >= totalItems) {
        loadMoreContainer.style.display = 'none';
    } else {
        loadMoreContainer.style.display = 'block';
    }
}

function formatNumberPlus(num) {
    if (num >= 100) return (Math.floor(num / 10) * 10) + "+";
    if (num >= 10) return (Math.floor(num / 10) * 10) + "+";
    return num.toString();
}

function updateCurrentCount() {
    const currentCountEl = document.getElementById('currentCount');
    const totalCountEl = document.getElementById('totalCount');
    
    const itemsShown = Math.min(currentPage * portfolioConfig.itemsPerPage, filteredData.length);
    
    currentCountEl.textContent = formatNumberPlus(itemsShown);
    totalCountEl.textContent = formatNumberPlus(filteredData.length);
}


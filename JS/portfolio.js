// VIDEO CONTROLS - SHOW ONLY ON HOVER + AUTO-PAUSE OTHERS
// ==========================================
function initVideoControls() {
    const videos = document.querySelectorAll('.video-wrapper video');
    
    videos.forEach(video => {
        const wrapper = video.closest('.video-wrapper');
        
        if (!wrapper) return;
        
        // Remove controls by default
        video.removeAttribute('controls');
        
        // Show controls on wrapper hover
        wrapper.addEventListener('mouseenter', function() {
            video.setAttribute('controls', 'controls');
        });
        
        // Hide controls when mouse leaves AND video is not playing
        wrapper.addEventListener('mouseleave', function() {
            if (video.paused) {
                video.removeAttribute('controls');
            }
        });
        
        // Keep controls visible while playing
        video.addEventListener('play', function() {
            video.setAttribute('controls', 'controls');
            
            // ✅ NEW: Pause all other videos when this one plays
            pauseAllOtherVideos(video);
        });
        
        // Hide controls when video is paused and mouse is not hovering
        video.addEventListener('pause', function() {
            if (!wrapper.matches(':hover')) {
                video.removeAttribute('controls');
            }
        });
        
        // Make video clickable to play/pause
        video.addEventListener('click', function(e) {
            // Don't interfere with control clicks
            if (e.target === video) {
                if (video.paused) {
                    video.play();
                } else {
                    video.pause();
                }
            }
        });
    });
}

// ==========================================
// PAUSE ALL OTHER VIDEOS
// ==========================================
function pauseAllOtherVideos(currentVideo) {
    const allVideos = document.querySelectorAll('.video-wrapper video');
    
    allVideos.forEach(video => {
        // If it's not the current video, pause it
        if (video !== currentVideo && !video.paused) {
            video.pause();
        }
    });
}



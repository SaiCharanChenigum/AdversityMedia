// Enhanced filter function to handle subcategories - SAME AS BEFORE
function filterPortfolio(filter) {
    if (filter === 'all') {
        filteredData = [...portfolioData];
    } else if (['education', 'healthcare', 'real-estate', 'spa-wellness', 'food-beverage'].includes(filter)) {
        // Show ALL projects with this subcategory (across all main categories)
        filteredData = portfolioData.filter(item => item.subcategory === filter);
    } else {
        // Regular category filter (branding, digital-marketing, social-media)
        filteredData = portfolioData.filter(item => item.category === filter);
    }
}


function displayPortfolioItems() {
    const container = document.getElementById('portfolioContainer');
    const itemsToShow = currentPage * portfolioConfig.itemsPerPage;
    const itemsToDisplay = filteredData.slice(0, itemsToShow);
    
    container.innerHTML = '';
    
    itemsToDisplay.forEach((item, index) => {
        const portfolioItem = createPortfolioItem(item, index);
        container.appendChild(portfolioItem);
    });
    
    updateLoadMoreButton();
    updateCurrentCount();
    
    // Reinitialize AOS for new items
    if (typeof AOS !== 'undefined') {
        AOS.refresh();
    }
}

function createPortfolioItem(item, index) {
    const col = document.createElement('div');
    col.className = 'col-lg-4 col-md-6 portfolio-item';
    col.setAttribute('data-category', item.category);
    col.setAttribute('data-aos', 'fade-up');
    col.setAttribute('data-aos-delay', (index % 3) * 100);
    
    const techTags = item.technologies.map(tech => 
        `<span class="tech-tag">${tech}</span>`
    ).join('');
    
    col.innerHTML = `
        <div class="portfolio-card">
            <div class="portfolio-image">
                <img src="${item.image}" alt="${item.title}" loading="lazy">
                <div class="portfolio-overlay">
                    <div class="portfolio-actions">
                        <button class="portfolio-action" onclick="openPortfolioModal(${item.id})">
                            <i class="fas fa-eye"></i>
                        </button>
                    </div>
                </div>
            </div>
            <div class="portfolio-content">
                <div class="portfolio-category">${portfolioConfig.categories[item.category]}</div>
                <h3 class="portfolio-title">${item.title}</h3>
                <p class="portfolio-description">${item.description}</p>
                <div class="portfolio-tech">
                    ${techTags}
                </div>
            </div>
        </div>
    `;
    
    return col;
}

